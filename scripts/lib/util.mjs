// Shared helpers for the setup scripts: env parsing, terminal prompts,
// Supabase Management API calls and console output. Node builtins only, so the
// installer runs before `npm install`.

import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");

const NO_COLOR = Boolean(process.env.NO_COLOR) || !process.stdout.isTTY;
const wrap = (code) => (s) => (NO_COLOR ? s : `\u001b[${code}m${s}\u001b[0m`);

export const c = {
  bold: wrap("1"),
  dim: wrap("2"),
  red: wrap("31"),
  green: wrap("32"),
  yellow: wrap("33"),
  blue: wrap("34"),
  cyan: wrap("36"),
};

export function banner(title) {
  const line = "=".repeat(Math.max(title.length + 4, 44));
  console.log("\n" + c.bold(line));
  console.log(c.bold("  " + title));
  console.log(c.bold(line) + "\n");
}

export function step(n, total, msg) {
  console.log("\n" + c.cyan(`[${n}/${total}]`) + " " + c.bold(msg));
}

export function ok(msg) {
  console.log("  " + c.green("ok") + "  " + msg);
}

export function info(msg) {
  console.log("  " + c.dim("-") + "   " + msg);
}

export function warn(msg) {
  console.log("  " + c.yellow("!") + "   " + msg);
}

export function fail(msg) {
  console.log("  " + c.red("x") + "   " + msg);
}

export function randomHex(bytes = 32) {
  return crypto.randomBytes(bytes).toString("hex");
}

// --- env files ---------------------------------------------------------------

export function parseEnv(text) {
  const out = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let val = line.slice(eq + 1).trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    out[key] = val;
  }
  return out;
}

export function loadEnv(dir = ROOT) {
  const merged = {};
  for (const file of [".env", ".env.local"]) {
    const p = path.join(dir, file);
    if (fs.existsSync(p)) Object.assign(merged, parseEnv(fs.readFileSync(p, "utf8")));
  }
  return merged;
}

export function writeEnvFile(pairs, dir = ROOT) {
  const target = path.join(dir, ".env.local");
  let backup = null;
  if (fs.existsSync(target)) {
    backup = `${target}.bak.${Date.now()}`;
    fs.copyFileSync(target, backup);
  }
  const lines = [
    "# Generated by scripts/install.mjs. Do not commit this file.",
    "# Buyer: keep these values secret. Only NEXT_PUBLIC_* are safe in the browser.",
    "",
  ];
  for (const [key, value] of pairs) lines.push(`${key}=${value ?? ""}`);
  lines.push("");
  fs.writeFileSync(target, lines.join("\n"), "utf8");
  return { target, backup };
}

// --- SQL files ---------------------------------------------------------------

export function orderSqlFiles(dir = path.join(ROOT, "supabase")) {
  const files = fs.readdirSync(dir).filter((f) => f.toLowerCase().endsWith(".sql"));
  const rank = (f) => {
    if (f === "schema.sql") return -1;
    if (f === "seed.sql") return 1e9;
    const m = /^(\d+)/.exec(f);
    return m ? Number(m[1]) : 1e8;
  };
  return files.sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));
}

export function readSql(name, dir = path.join(ROOT, "supabase")) {
  return fs.readFileSync(path.join(dir, name), "utf8");
}

// --- Supabase ----------------------------------------------------------------

export function projectRefFromUrl(url) {
  const host = url.replace(/^https?:\/\//i, "").replace(/\/.*$/, "");
  const ref = host.split(".")[0];
  return ref || null;
}

export async function restCheck(url, key, table = "settings") {
  const res = await fetch(`${url}/rest/v1/${table}?select=id&limit=1`, {
    headers: { apikey: key, Authorization: `Bearer ${key}` },
  });
  // 200 means the table answered. 404 means the key works but the table is
  // missing (schema not applied yet). Either way the credentials are valid.
  return { status: res.status, ok: res.ok, missingTable: res.status === 404 };
}

export async function runSql(pat, ref, sql) {
  const res = await fetch(`https://api.supabase.com/v1/projects/${ref}/database/query`, {
    method: "POST",
    headers: {
      Authorization: `Bearer ${pat}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify({ query: sql }),
  });
  const body = await res.text();
  if (!res.ok) throw new Error(`HTTP ${res.status}: ${body.slice(0, 600)}`);
  return body;
}

export async function scaffoldCheck(pat, ref) {
  const body = await runSql(pat, ref, "select count(*)::int as n from public.settings;");
  const n = extractCount(body);
  return n;
}

export function extractCount(body) {
  try {
    const parsed = JSON.parse(body);
    if (Array.isArray(parsed)) return parsed[0]?.n ?? parsed[0]?.count ?? null;
    if (parsed && typeof parsed === "object") {
      if (typeof parsed.n === "number") return parsed.n;
      if (Array.isArray(parsed.value)) return parsed.value[0]?.n ?? null;
    }
  } catch {
    /* not json */
  }
  return null;
}

// --- prompts -----------------------------------------------------------------

export class Prompt {
  constructor() {
    this.rawWasSet = false;
  }

  // A tiny raw-mode line reader so plain and hidden prompts can share one stdin.
  _read(question, { hidden = false, def = "" } = {}) {
    return new Promise((resolve) => {
      const stdin = process.stdin;
      const canRaw = typeof stdin.setRawMode === "function";
      const wasRaw = stdin.isRaw;
      if (canRaw) stdin.setRawMode(true);
      stdin.resume();

      const suffix = def !== "" && def != null ? c.dim(` [${hidden ? "hidden" : def}]`) : "";
      process.stdout.write(question + suffix + " ");

      let buf = "";
      const done = (value) => {
        stdin.removeListener("data", onData);
        if (canRaw) stdin.setRawMode(Boolean(wasRaw));
        stdin.pause();
        resolve(value);
      };
      const onData = (chunk) => {
        const s = chunk.toString("utf8");
        for (let i = 0; i < s.length; i++) {
          const ch = s[i];
          if (ch === "\u001b") {
            i += 2; // drop a 3-byte escape sequence (arrow keys, etc.)
            continue;
          }
          if (ch === "\r" || ch === "\n") {
            process.stdout.write("\n");
            return done(buf || def);
          }
          if (ch === "\u0003") {
            process.stdout.write("\n");
            process.exit(130);
          }
          if (ch === "\u007f" || ch === "\b") {
            if (buf.length) {
              buf = buf.slice(0, -1);
              process.stdout.write("\b \b");
            }
            continue;
          }
          if (ch < " ") continue;
          buf += ch;
          process.stdout.write(hidden ? "*" : ch);
        }
      };
      stdin.on("data", onData);
    });
  }

  async text(question, opts = {}) {
    const value = await this._read(question, opts);
    return (value ?? "").trim();
  }

  async secret(question) {
    return this._read(question, { hidden: true });
  }

  async confirm(question, def = true) {
    const hint = def ? "[Y/n]" : "[y/N]";
    const answer = (await this._read(`${question} ${c.dim(hint)}`)).trim().toLowerCase();
    if (!answer) return def;
    return answer === "y" || answer === "yes";
  }

  async required(question, validate, opts = {}) {
    for (;;) {
      const value = opts.hidden ? await this.secret(question) : await this.text(question, opts);
      const problem = validate ? validate(value) : null;
      if (!value) {
        warn("This value is required.");
        continue;
      }
      if (problem) {
        warn(problem);
        continue;
      }
      return value;
    }
  }

  async choice(question, options, def = 0) {
    console.log(question);
    options.forEach((o, i) => console.log(`  ${i + 1}) ${o}`));
    for (;;) {
      const raw = (await this.text(`Choose 1-${options.length}`, { def: String(def + 1) })).trim();
      const n = Number(raw);
      if (Number.isInteger(n) && n >= 1 && n <= options.length) return n - 1;
      warn(`Enter a number between 1 and ${options.length}.`);
    }
  }

  close() {
    try {
      process.stdin.pause();
    } catch {
      /* ignore */
    }
  }
}
